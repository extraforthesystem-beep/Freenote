import CoreGraphics

/// The app's corner radii, for cards, panels, chips and controls. 10 is on the
/// scale because it is the most used radius in the app today.
enum AppRadius {
    static let xs: CGFloat = 4
    static let s: CGFloat = 8
    static let m: CGFloat = 10
    static let l: CGFloat = 12
    static let xl: CGFloat = 16
    static let xxl: CGFloat = 20
}
